#!/usr/bin/env bash
# Build the prepackaged installer for the current operating system.
# Linux:  install_linux (single Bash file, no external source modules required)
# macOS:  install_macos (single Bash file, embeds compiled Darwin executable/dylib)
set -Eeuo pipefail
IFS=$'\n\t'

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
OS=$(uname -s)

checksum() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1"
    else
        shasum -a 256 "$1"
    fi
}

build_linux() {
    local output="$ROOT/install_linux" temp module
    local -a modules=()
    temp=$(mktemp "$ROOT/.install_linux.XXXXXX")
    trap "rm -f '$temp'" EXIT

    mapfile -t modules < <(find "$ROOT/src" -maxdepth 1 -type f -name '[0-9][0-9]-*.sh' | sort)
    (( ${#modules[@]} > 0 )) || {
        printf 'ERROR: no source modules found under %s/src\n' "$ROOT" >&2
        exit 1
    }
    for module in "${modules[@]}"; do
        bash -n "$module"
        cat "$module" >> "$temp"
        printf '\n' >> "$temp"
    done
    bash -n "$temp"
    python3 "$ROOT/tools/check_embedded_python.py" "$temp"
    install -m 0755 "$temp" "$output"
    printf 'Built %s\n' "$output"
    checksum "$output"
}

build_macos() {
    local output="$ROOT/install_macos" stage payload script
    [ "$(id -u)" -ne 0 ] || {
        printf 'ERROR: build.sh must be run as a regular user; use sudo only to run install_macos.\n' >&2
        exit 1
    }
    command -v clang >/dev/null 2>&1 || {
        printf 'ERROR: Apple clang is required (xcode-select --install).\n' >&2
        exit 1
    }
    command -v make >/dev/null 2>&1 || {
        printf 'ERROR: make is required (Xcode Command Line Tools).\n' >&2
        exit 1
    }
    # The bundled launcher and DYLD interposer are compiled on the target Mac.
    make -C "$ROOT/macos" all
    bash "$ROOT/macos/tests/test-static.sh"
    local binary
    for binary in "$ROOT/macos/bin/nns-run" "$ROOT/macos/bin/libnnsbind.dylib"; do
        if ! file -b "$binary" | grep -q 'Mach-O'; then
            printf 'ERROR: expected a native Mach-O binary: %s\n' "$binary" >&2
            exit 1
        fi
    done

    stage=$(mktemp -d "$ROOT/.install_macos.XXXXXX")
    trap "rm -rf '$stage'" EXIT
    mkdir -p "$stage/macos/bin"
    install -m 0755 "$ROOT/macos/install.sh" "$stage/macos/install.sh"
    install -m 0755 "$ROOT/macos/nns-app-darwin.sh" "$stage/macos/nns-app-darwin.sh"
    install -m 0755 "$ROOT/macos/bin/nns-run" "$stage/macos/bin/nns-run"
    install -m 0755 "$ROOT/macos/bin/libnnsbind.dylib" "$stage/macos/bin/libnnsbind.dylib"

    payload="$stage/payload.tar.gz"
    tar -czf "$payload" -C "$stage" \
        macos/install.sh macos/nns-app-darwin.sh \
        macos/bin/nns-run macos/bin/libnnsbind.dylib

    script="$stage/installer"
    cat > "$script" <<'INSTALLER'
#!/bin/bash
# nns-app 2.1.0: self-contained macOS installer with precompiled C binaries.
# Generated by build.sh on macOS. Source files and clang are not needed to install.
set -euo pipefail
[ "$(uname -s)" = Darwin ] || { echo 'ERROR: install_macos is macOS only.' >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || { echo 'ERROR: run sudo ./install_macos.' >&2; exit 1; }

TMP_NNS_INSTALL=$(mktemp -d "${TMPDIR:-/tmp}/nns-app-install.XXXXXX")
trap 'rm -rf "$TMP_NNS_INSTALL"' EXIT

# No network or repository access is needed to unpack the prebuilt application.
# Runtime WireGuard and developer-tool dependencies are handled by macos/install.sh.
# LC_ALL=C avoids "tar: Failed to set default locale" under sudo (stripped LANG).
awk '/^__NNS_APP_MACOS_PAYLOAD_BEGIN__$/ { data=1; next } data { print }' "$0" \
    | /usr/bin/base64 -D \
    | LC_ALL=C LANG=C /usr/bin/tar -xz -C "$TMP_NNS_INSTALL"
"$TMP_NNS_INSTALL/macos/install.sh" "$@"
exit 0
__NNS_APP_MACOS_PAYLOAD_BEGIN__
INSTALLER
    # macOS BSD base64 wraps lines by default; the decoder accepts the same format.
    base64 < "$payload" >> "$script"
    install -m 0755 "$script" "$output"
    printf 'Built %s (precompiled macOS payload included)\n' "$output"
    checksum "$output"
}

case "$OS" in
    Linux) build_linux ;;
    Darwin) build_linux; build_macos ;;
    *) printf 'ERROR: unsupported build host: %s\n' "$OS" >&2; exit 1 ;;
esac
